import {Hono} from 'hono';
import {cors} from 'hono/cors';
import {bodyLimit} from 'hono/body-limit';
import type {AppEnv} from './types';
import {ApiError} from './types';
import auth from './http/auth';
import tickets from './http/tickets';
import operations from './http/operations';
import webhook from './http/webhook';
import {runJobs,processQueue} from './jobs/process';
const app=new Hono<AppEnv>();
app.onError((e,c)=>{if(!(e instanceof ApiError))console.error('[ticket] request failed',c.env.ENVIRONMENT==='development'?e.message:e.name);return c.json({error:e instanceof ApiError?e.message:'Request could not be completed; inspect service logs'},(e instanceof ApiError?e.status:500) as any);});
app.use('/integrations/*',bodyLimit({maxSize:1024*1024}));
app.use('/api/*',bodyLimit({maxSize:11*1024*1024}));
app.use('/api/*',cors({origin:(origin,c)=>origin===c.env.ALLOWED_ORIGIN?origin:'',allowMethods:['GET','POST','PUT','OPTIONS'],allowHeaders:['Content-Type','Cf-Access-Jwt-Assertion','X-Dev-Staff-Id','Idempotency-Key'],credentials:true,maxAge:600}));
app.use('/api/*',async(c,next)=>{const origin=c.req.header('origin');if(!['GET','HEAD','OPTIONS'].includes(c.req.method)&&origin&&origin!==c.env.ALLOWED_ORIGIN)return c.json({error:'Untrusted request origin'},403);await next();});
app.use('/api/*',auth);app.route('/',tickets);app.route('/',operations);app.route('/',webhook);
app.get('/health',c=>c.json({status:'ok',service:'masci-line-ticket',environment:c.env.ENVIRONMENT}));
export default {fetch:app.fetch,async scheduled(_event:ScheduledController,env:AppEnv['Bindings'],ctx:ExecutionContext){ctx.waitUntil(runJobs(env));},async queue(batch:MessageBatch,env:AppEnv['Bindings']){for(const m of batch.messages){try{await processQueue(env,m);m.ack();}catch{m.retry({delaySeconds:30});}}}};
